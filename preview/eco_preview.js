import * as THREE from 'three';
import { RoomEnvironment } from 'three/examples/jsm/environments/RoomEnvironment.js';
import { EffectComposer } from 'three/examples/jsm/postprocessing/EffectComposer.js';
import { RenderPass } from 'three/examples/jsm/postprocessing/RenderPass.js';
import { UnrealBloomPass } from 'three/examples/jsm/postprocessing/UnrealBloomPass.js';
import { OutputPass } from 'three/examples/jsm/postprocessing/OutputPass.js';
import { makeEco, drawEcoFace } from '../src/eco.js';
import { redraw } from '../src/util.js';

// Iluminación equivalente a slide1 (exterior soleado)
const W = 1280, H = 720;
const renderer = new THREE.WebGLRenderer({ antialias: true, preserveDrawingBuffer: true });
renderer.setSize(W, H); renderer.setPixelRatio(1);
renderer.domElement.style.cssText = 'display:block';
renderer.outputColorSpace = THREE.SRGBColorSpace;
renderer.toneMapping = THREE.ACESFilmicToneMapping;
renderer.toneMappingExposure = 0.82;
renderer.shadowMap.enabled = true; renderer.shadowMap.type = THREE.PCFSoftShadowMap;
document.body.style.margin = '0'; document.body.appendChild(renderer.domElement);
const scene = new THREE.Scene();
scene.background = new THREE.Color(0x9cc4dc);
const pm = new THREE.PMREMGenerator(renderer);
scene.environment = pm.fromScene(new RoomEnvironment(), 0.04).texture;
scene.environmentIntensity = 0.55;
const sun = new THREE.DirectionalLight(0xffe8c8, 3.0); sun.position.set(4, 8, 5); sun.castShadow = true;
sun.shadow.mapSize.set(2048, 2048); Object.assign(sun.shadow.camera, { left: -3, right: 3, top: 3, bottom: -3 });
sun.shadow.bias = -0.0004; sun.shadow.normalBias = 0.02; scene.add(sun);
scene.add(new THREE.HemisphereLight(0xcfe6ff, 0x8a9a7a, 0.7));
const ground = new THREE.Mesh(new THREE.PlaneGeometry(20, 20), new THREE.MeshStandardMaterial({ color: 0xa89a8a, roughness: 0.9 }));
ground.rotation.x = -Math.PI / 2; ground.receiveShadow = true; scene.add(ground);
const camera = new THREE.PerspectiveCamera(30, W / H, 0.05, 50);
camera.position.set(0, 1.2, 5.6); camera.lookAt(0, 1.05, 0);
const t0 = performance.now();
const eco = makeEco();
window.buildMs = performance.now() - t0;
scene.add(eco);
const composer = new EffectComposer(renderer);
composer.addPass(new RenderPass(scene, camera));
const bloom = new UnrealBloomPass(new THREE.Vector2(W, H), 0.7, 0.45, 2.3); composer.addPass(bloom); window.bloom = bloom;
composer.addPass(new OutputPass());
window.eco = eco; window.THREE = THREE; window.camera = camera; window.renderer = renderer;
window.render = () => { composer.render(); return renderer.info.render; };
window.setPose = (p, yaw = 0, mood = 'idle') => {
  eco.rotation.y = yaw;
  for (let i = 0; i < 90; i++) eco.userData.update(1 / 30, i / 30, p, true);
  redraw(eco.userData.faceTex, (ctx, w, h) => drawEcoFace(ctx, w, h, mood, 0, 0));
  composer.render();
  let meshes = 0; eco.traverse((o) => { if (o.isMesh) meshes++; });
  return { meshes };
};
window.cam = (x, y, z, tx = 0, ty = 1.05, tz = 0, fov = 30) => { camera.position.set(x, y, z); camera.fov = fov; camera.updateProjectionMatrix(); camera.lookAt(tx, ty, tz); composer.render(); };
window.countTris = () => { let t = 0; eco.traverse((o) => { if (o.isMesh) { const g = o.geometry; t += (g.index ? g.index.count : g.attributes.position.count) / 3; } }); return t; };
window.topTris = () => { const a = []; eco.traverse((o) => { if (o.isMesh) { const g = o.geometry; a.push([((g.index ? g.index.count : g.attributes.position.count) / 3) | 0, o.material.name || o.material.color?.getHexString(), o.parent?.name]); } }); return a.sort((x, y) => y[0] - x[0]).slice(0, 12); };
window.bbox = () => new THREE.Box3().setFromObject(eco);
window.setPose('idle');
